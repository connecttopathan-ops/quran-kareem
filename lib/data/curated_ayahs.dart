class CuratedAyah {
  final int surah;
  final int ayah;
  final String surahName;
  final String arabic;

  /// The verse excerpt, by language code. `'en'` is always present and is the
  /// fallback.
  ///
  /// Deliberately an excerpt, not the whole verse — these are sized for a
  /// home-screen card and a notification body. Note they also differ from the
  /// bundled Quran translations in `assets/translations/`: those render الله
  /// as "God" and give the verse in full, while these say "Allah" and are
  /// cut to fit. The two are not interchangeable.
  final Map<String, String> translations;

  /// The app's own one-line reflection on the verse, by language code.
  ///
  /// This is editorial voice, not scripture — translate it as ordinary prose.
  final Map<String, String> messages;

  const CuratedAyah({
    required this.surah,
    required this.ayah,
    required this.surahName,
    required this.arabic,
    required this.translations,
    required this.messages,
  });

  /// The verse excerpt in [languageCode], falling back to English.
  String translation(String languageCode) =>
      translations[languageCode] ?? translations['en'] ?? '';

  /// The reflection in [languageCode], falling back to English.
  String message(String languageCode) =>
      messages[languageCode] ?? messages['en'] ?? '';
}

