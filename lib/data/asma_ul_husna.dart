import 'package:flutter/material.dart';

class AsmaEntry {
  final int number;
  final String arabic;
  final String transliteration;

  /// The name's meaning, by language code.
  ///
  /// Kept here beside the Arabic rather than in the ARB for two reasons. The
  /// generated localisations expose named getters, not a lookup, so there is
  /// no way to ask them for "the meaning of name 47" without a 99-case
  /// switch. And these are Names of Allah: holding every rendering next to
  /// the Arabic it translates lets a qualified reviewer check one entry in
  /// one place, rather than cross-referencing six files by key.
  ///
  /// `'en'` is always present and is the fallback.
  final Map<String, String> meanings;

  const AsmaEntry({
    required this.number,
    required this.arabic,
    required this.transliteration,
    required this.meanings,
  });

  /// The meaning in [languageCode], falling back to English.
  ///
  /// Falls back rather than returning null so a locale we have not finished
  /// translating shows the English name instead of an empty card.
  String meaning(String languageCode) =>
      meanings[languageCode] ?? meanings['en'] ?? '';
}

